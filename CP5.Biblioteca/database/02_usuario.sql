-- Execute uma única vez no mesmo schema em que já executou oracle.sql.
-- Não é necessário recriar CP5_LIVRO nem CP5_EMPRESTIMO.
CREATE TABLE CP5_USUARIO (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NOME NVARCHAR2(120) NOT NULL,
    EMAIL NVARCHAR2(160) NOT NULL,
    PASSWORD NVARCHAR2(120) NOT NULL,
    ROLE NVARCHAR2(20) DEFAULT 'leitor' NOT NULL,
    CONSTRAINT UK_CP5_USUARIO_EMAIL UNIQUE (EMAIL)
);
-- Administradores sao criados via POST /api/auth/registrar-admin, sem JWT.
-- Leitores sao criados via POST /api/auth/registrar, tambem sem JWT.
